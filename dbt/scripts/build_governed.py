"""Write the governed tables' dbt models from MetricFlow's compiled SQL (semantic/PLAN.md SL-24, #314).

For each table governed.py plans, MetricFlow compiles the query that is the table, offline, in the target's
dialect, and this writes it as a dbt model whose only change is each relation MetricFlow names turned back into
its `ref()`, so dbt orders the build and the model follows the target's project:
- `<home>_daily`: the additive metrics grouped by `metric_time__day` and the table's dimensions, one query;
- `<home>_by_period`: one query per grain (day, ISO week, month) for the whole period, and per dimension by day,
  each MetricFlow's own, stacked with `union all` under `grain`, `period_start`, `slice` and `slice_value`.
No SQL here computes a number: every aggregate, join, filter, ratio, window and offset is MetricFlow's.
Beside the models, `governed.yml` holds every table's and column's description (governed.py), which
`persist_docs` writes to BigQuery.

The models are BigQuery's (dbt_project.yml enables the folder on a BigQuery target only): the governed tables
serve a native BigQuery data agent, so this runs on the compile-only `bigquery` target, where MetricFlow writes
BigQuery's dialect. `make governed-models` writes them into dbt/models/governed/ (tests/e2e/governed-models.sh);
`make bigquery-check` fails when they differ from what this writes now.

Usage, from a dbt project parsed on the bigquery target: python scripts/build_governed.py target models/governed
"""

from __future__ import annotations

import functools
import importlib.util
import json
import os
import re
import sys
from pathlib import Path

import yaml
from build_catalog import SemanticIndex, _metricflow
from governed import GRAINS, TIME, TOTAL, Table, column_descriptions, plan, table_description


def _bigquery_sql():
    """The semantic agent's `bigquery_sql` module, which quotes the reserved-word names MetricFlow leaves bare
    (#322): the one copy the agent's queries and these models share, loaded by its path, since the agent's package
    imports ADK. `SEMANTIC_AGENT_SRC` names the package's folder (tests/e2e/governed-models.sh runs on a copy of
    dbt/); else the checkout's."""
    default = Path(__file__).resolve().parents[2] / "services" / "semantic-agent" / "src" / "semantic_agent"
    path = Path(os.environ.get("SEMANTIC_AGENT_SRC", default)) / "bigquery_sql.py"
    spec = importlib.util.spec_from_file_location("bigquery_sql", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


quote_reserved = _bigquery_sql().quote_reserved

HEADER = (
    "-- Generated by dbt/scripts/build_governed.py from MetricFlow's compiled SQL (semantic/PLAN.md SL-24):\n"
    "-- do not edit; `make governed-models` rewrites it from the semantic layer.\n"
)


SEPARATOR = ",\n  "


def refs(manifest: dict) -> dict[str, str]:
    """Each model's relation as MetricFlow's BigQuery SQL names it, `` `project`.`dataset`.`table` ``, to its ref."""
    found = {}
    for node in manifest["nodes"].values():
        if node["resource_type"] == "model" and node.get("database"):
            relation = f"`{node['database']}`.`{node['schema']}`.`{node['alias']}`"
            found[relation] = "{{ ref('" + node["name"] + "') }}"
    return found


def as_model(sql: str, relations: dict[str, str]) -> str:
    """MetricFlow's SQL with its relations as refs and reserved-word names quoted; any other backticked
    relation, or Jinja, is refused."""
    if any(mark in sql for mark in ("{{", "{%", "{#")):
        raise ValueError("MetricFlow's SQL holds a Jinja delimiter")
    named = re.compile(r"`[^`]+`\.`[^`]+`\.`[^`]+`")
    unknown = sorted({relation for relation in named.findall(sql) if relation not in relations})
    if unknown:
        raise ValueError(f"MetricFlow's SQL reads relations no model builds: {unknown}")
    return named.sub(lambda m: relations[m[0]], quote_reserved(sql))


def _indent(sql: str) -> str:
    return "\n".join(f"  {line}" if line else line for line in sql.strip().splitlines())


def daily_sql(table: Table, compiled, relations: dict[str, str]) -> str:
    sql = as_model(compiled(list(table.metrics), [TIME, *table.dimensions]), relations)
    columns = [f"cast({TIME} as date) as {TIME}", *table.dimensions, *table.metrics]
    return f"select\n  {SEPARATOR.join(columns)}\nfrom (\n{_indent(sql)}\n) as metricflow\n"


def by_period_sql(table: Table, compiled, relations: dict[str, str]) -> str:
    parts = []
    for grain in GRAINS:
        time = f"metric_time__{grain}"
        # Breakdowns by one dimension on days only: a week's or a month's comes in whole.
        for dimension in (None, *(table.dimensions if grain == "day" else ())):
            sql = as_model(compiled(list(table.metrics), [time, *([dimension] if dimension else [])]), relations)
            columns = [
                f"'{grain}' as grain",
                f"cast({time} as date) as period_start",
                f"'{dimension or TOTAL}' as slice",
                f"cast({dimension} as string) as slice_value" if dimension else "cast(null as string) as slice_value",
                *table.metrics,
            ]
            parts.append(f"select\n  {SEPARATOR.join(columns)}\nfrom (\n{_indent(sql)}\n) as metricflow\n")
    return "union all\n".join(parts)


def main() -> int:
    target = Path(sys.argv[1] if len(sys.argv) > 1 else "target")
    out = Path(sys.argv[2] if len(sys.argv) > 2 else "models/governed")
    manifest = json.loads((target / "manifest.json").read_text())
    semantic_manifest = json.loads((target / "semantic_manifest.json").read_text())
    if manifest["metadata"].get("adapter_type") != "bigquery":
        print("build_governed: the governed models are BigQuery's; parse on the bigquery target", file=sys.stderr)
        return 2
    index = SemanticIndex(manifest, semantic_manifest)
    metricflow = _metricflow(Path(__file__).resolve().parents[1], index)
    dimensions_of = functools.cache(metricflow.dimensions)
    tables = plan(index.metrics, dimensions_of)
    metrics = {metric["name"]: metric for metric in index.metrics}
    relations = refs(manifest)

    out.mkdir(parents=True, exist_ok=True)
    models = []
    for table in tables:
        body = (daily_sql if table.kind == "daily" else by_period_sql)(table, metricflow.compiled, relations)
        config = "{{ config(alias='" + table.name + "') }}\n\n"
        (out / f"{table.model}.sql").write_text(HEADER + config + body)
        dimensions = {
            dimension["name"]: dimension.get("description") or ""
            for name in table.metrics
            for dimension in dimensions_of(name)
        }
        columns = column_descriptions(table, metrics, tables, dimensions)
        models.append(
            {
                "name": table.model,
                "description": table_description(table),
                "config": {
                    "meta": {"governed": {"kind": table.kind, "home": table.home, "metrics": list(table.metrics)}}
                },
                "columns": [{"name": name, "description": text} for name, text in columns.items()],
            }
        )
    document = yaml.safe_dump({"version": 2, "models": models}, sort_keys=False, allow_unicode=True, width=110)
    (out / "governed.yml").write_text(
        "# Generated by dbt/scripts/build_governed.py (semantic/PLAN.md SL-24): do not edit; `make governed-models`.\n"
        + document
    )
    print(
        f"build_governed: {len(tables)} governed tables in {out}: "
        f"{sum(t.kind == 'daily' for t in tables)} daily, {sum(t.kind == 'by_period' for t in tables)} by period"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
