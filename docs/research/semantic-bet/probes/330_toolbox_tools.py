"""Generate MCP Toolbox's tools file from the `native-shaped` arm's table functions (offline).

What it does: reads probes/329_bet_shaped.sql, finds every
`CREATE OR REPLACE TABLE FUNCTION bet_shaped.<name>(start_date DATE, end_date DATE)` and its description,
and writes probes/330_tools.yaml in Toolbox's flat format (1.x): one BigQuery source with
`useClientOAuth: true` (the caller's token reaches BigQuery, as at work), one `bigquery-sql` tool per table
function and one toolset, `bet-shaped`, holding them all.
Toolbox's parameter types have no DATE, so each tool takes two ISO-date strings and casts them.

Run from the repo root (offline, standard library only):
    python docs/research/semantic-bet/probes/330_toolbox_tools.py [--project <id>] [--check]
`--check` exits 1 when the committed tools file differs from what the SQL generates now.
Env: none. Live: no; probes/330_toolbox_check.sh loads the file into a pinned Toolbox with no network.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SQL = HERE / "329_bet_shaped.sql"
OUT = HERE / "330_tools.yaml"
SOURCE = "lab-bigquery"
TOOLSET = "bet-shaped"

FUNCTION = re.compile(
    r"CREATE OR REPLACE TABLE FUNCTION bet_shaped\.(?P<name>\w+)\((?P<args>[^)]*)\)\s*\n"
    r"OPTIONS \(description = '(?P<description>(?:[^'\\]|\\.)*)'\)"
)
EXPECTED_ARGS = "start_date DATE, end_date DATE"


def functions(sql: str) -> list[tuple[str, str]]:
    """The (name, description) of every table function in the script, in its order."""
    found = []
    for match in FUNCTION.finditer(sql):
        if match["args"] != EXPECTED_ARGS:
            raise ValueError(
                f"{match['name']}: arguments {match['args']!r}, expected {EXPECTED_ARGS!r}"
            )
        found.append((match["name"], match["description"].replace("\\'", "'")))
    if not found:
        raise ValueError(f"no table function found in {SQL.name}")
    return found


def quoted(text: str) -> str:
    """A YAML single-quoted scalar."""
    return "'" + text.replace("'", "''") + "'"


def tools_yaml(project: str, found: list[tuple[str, str]]) -> str:
    docs = [
        "\n".join(
            [
                "# Generated by probes/330_toolbox_tools.py from probes/329_bet_shaped.sql; do not edit by hand.",
                "kind: source",
                f"name: {SOURCE}",
                "type: bigquery",
                f"project: {project}",
                "location: US",
                "useClientOAuth: true",
            ]
        )
    ]
    for name, description in found:
        docs.append(
            "\n".join(
                [
                    "kind: tool",
                    f"name: {name}",
                    "type: bigquery-sql",
                    f"source: {SOURCE}",
                    f"description: {quoted(description)}",
                    "statement: "
                    + quoted(
                        f"SELECT * FROM bet_shaped.{name}(CAST(@start_date AS DATE), CAST(@end_date AS DATE))"
                    ),
                    "parameters:",
                    "- name: start_date",
                    "  type: string",
                    "  description: The first day, inclusive, as YYYY-MM-DD.",
                    "- name: end_date",
                    "  type: string",
                    "  description: The last day, inclusive, as YYYY-MM-DD.",
                ]
            )
        )
    docs.append(
        "\n".join(
            [
                "kind: toolset",
                f"name: {TOOLSET}",
                "tools:",
                *(f"- {n}" for n, _ in found),
            ]
        )
    )
    return "\n---\n".join(docs) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--project", default="pplk8s-lab-001")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = tools_yaml(args.project, functions(SQL.read_text()))
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.name} is stale: rerun without --check", file=sys.stderr)
            return 1
        print(f"{OUT.name} is current")
        return 0
    OUT.write_text(text)
    print(
        f"wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
